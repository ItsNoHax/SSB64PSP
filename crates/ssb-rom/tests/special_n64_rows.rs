/// A `jtrace.py` route (`start:len:keys;...` in N64 frames, keys `a b z
/// c_u x=.. y=..`) as the pad at host tick `tick` (N64 frame `tick - 4`).
fn route_pad(route: &str, tick: u64) -> (u16, i8, i8) {
    let t = tick.wrapping_sub(4);
    let mut out = (0u16, 0i8, 0i8);
    for step in route.split(';') {
        let mut it = step.split(':');
        let start: u64 = it.next().unwrap().parse().unwrap();
        let len: u64 = it.next().unwrap().parse().unwrap();
        if !(start..start + len).contains(&t) {
            continue;
        }
        for key in it.next().unwrap().split('+') {
            match key.split_once('=') {
                Some(("x", v)) => out.1 = v.parse().unwrap(),
                Some(("y", v)) => out.2 = v.parse().unwrap(),
                _ => {
                    out.0 |= match key {
                        "a" => script::button::A,
                        "b" => script::button::B,
                        "z" => script::button::Z,
                        "c_u" => script::button::C_UP,
                        _ => panic!("route key {key}"),
                    }
                }
            }
        }
    }
    out
}

/// Pikachu runs right, brakes, turns left, jumps back (`JumpB`, 23) off
/// the right edge and drifts back; the Quick Attack's B at frame 147
/// zeroes `vel_air` (`SpecialAirHiStart`, 235). Falling at gravity 0.8
/// along the right wall, the hand (TopN + (-400, 280)) crosses the
/// cliff-flagged floor at frame 159: `mpCommonProcFighterCliff` sets
/// `CliffCatch` (84) from the start, then `CliffWait` (85) at 162.
const PIKACHU_ROUTE: &str =
    "26:38:x=80;64:6:x=-80;100:3:c_u+x=80;103:12:x=80;125:22:x=-80;147:1:b+y=80";

/// Pikachu's Quick Attack start catches the ledge (`allows_cliff`).
#[cfg_attr(ssb64_stub_tables, ignore = "needs the ROM-generated tables")]
#[test]
fn quick_attack_start_catches_the_ledge_like_the_n64() {
    const DREAM_LAND: u32 = 0;
    let pad = |t: u64| route_pad(PIKACHU_ROUTE, t);
    check_pad(
        "Pikachu ledge",
        &pad,
        FighterKind::Pikachu,
        DREAM_LAND,
        false,
        PIKACHU,
    );
}


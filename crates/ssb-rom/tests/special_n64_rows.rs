//! Specials on a slope, against a moving wall and in the air, tick by tick
//! against the N64 (batch 38): Captain Falcon's Falcon Kick on Peach's
//! Castle rolls along the moving side lens's right wall (line 14, group 4),
//! Kirby's Stone slides down Kongo Jungle's slope, and Ness's PK Thunder
//! head, steered back into him on Dream Land, launches the jibaku, and
//! Pikachu's Quick Attack start catches Dream Land's right ledge.
//!
//! Rows: N64 frame `t` is host tick `t + 4`. Warp ROMs (Training, Mario
//! dummy port 1), traced headless; pads in N64 frames:
//! - Captain, Castle: `4:1:a;26:2:x=-80;56:1:b+y=-80`;
//! - Kirby, Jungle: `4:1:a;26:12:x=80;116:1:b+y=-80`;
//! - Ness, Dream Land:
//!   `4:1:a;26:27:x=80;76:1:c_u;136:1:b+y=80;171:21:x=57+y=-57;192:100:x=-80`;
//! - Pikachu, Dream Land: [`PIKACHU_ROUTE`].
//!
//! Each row holds the player's status id, facing, airborne flag, `vel_air`
//! x/y, TopN x/y, TopN rotate x/z and joint 4's rotate as `f32` bits. The traces stay local
//! (D-048); the bits are the comparison.
use ssb_capture::script;
use ssb_capture::GameScene;
use ssb_game::fighter::FighterKind;

#[path = "common/posed.rs"]
mod posed;
use posed::{tick_pair, Pair, Posed};

#[path = "common/dream_land.rs"]
mod dream_land;
use dream_land::{dream_land_map, map_groups, stage_floors, training_fighter};

struct Row {
    tick: u64,
    status: u32,
    lr: i32,
    air: bool,
    vel: [u32; 2],
    pos: [u32; 2],
    rot: [u32; 2],
    joint4: [u32; 3],
}

fn open_pack() -> Option<Vec<u8>> {
    ssb_tablegen::test_rom(env!("CARGO_MANIFEST_DIR"))?;
    let path =
        std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../assets/generated/ssb64.pak");
    std::fs::read(path).ok()
}

/// [`check_pad`] on `scene`'s scripted pad.
fn check(scene: GameScene, kind: FighterKind, stage_index: u32, groups: bool, rows: &[Row]) {
    let pad = |t: u64| {
        let p = script::fighter_pad(scene, t).unwrap();
        (p.buttons, p.stick_x, p.stick_y)
    };
    check_pad(&format!("{scene:?}"), &pad, kind, stage_index, groups, rows);
}

/// Replays `kind` against a Mario dummy on `pad` (host ticks) to the last
/// row and compares every row exactly. `groups` runs the stage's moving
/// groups, already at N64 frame 4 when the replay starts at tick 8.
fn check_pad(
    what: &str,
    pad: &dyn Fn(u64) -> (u16, i8, i8),
    kind: FighterKind,
    stage_index: u32,
    groups: bool,
    rows: &[Row],
) {
    let Some(bytes) = open_pack() else {
        return;
    };
    let pack = ssb_rom::pack::Pack::open(&bytes).unwrap();
    let (stage, segments) = stage_floors(&pack, stage_index);
    let map = dream_land_map(&pack, &stage);
    let mut fighters: Vec<Posed> = [(kind, 0), (FighterKind::Mario, 1)]
        .into_iter()
        .map(|(kind, port)| {
            Posed::new(
                &pack,
                training_fighter(&pack, &stage, kind, port, &segments),
            )
        })
        .collect();
    let mut pair = Pair::default();
    if groups {
        let mut g = ssb_pose::ground::StageGroups::new(&pack, stage_index, &stage);
        for _ in 0..4 {
            g.tick(&pack).unwrap();
        }
        pair.groups = Some((g, map_groups(&pack, &stage)));
    }
    let mut rows = rows.iter().peekable();
    let last = rows.clone().last().unwrap().tick;
    for tick in 8..=last {
        let _ = tick_pair(&pack, &map, &mut fighters, pad, tick, &mut pair);
        let Some(row) = rows.next_if(|r| r.tick == tick) else {
            continue;
        };
        let m = &fighters[0];
        let f = &m.fighter;
        let first = pack.object(m.object).map(|o| o.first_node).unwrap();
        let joint4 = m
            .skeleton
            .node_pose(first)
            .unwrap()
            .rotate
            .map(f32::to_bits);
        let got = (
            u32::from(f.status.status.id()),
            f.facing.sign() as i32,
            !f.is_grounded(),
            [f.physics.vel_air.x.to_bits(), f.physics.vel_air.y.to_bits()],
            [f.pos.x.to_bits(), f.pos.y.to_bits()],
            [f.topn_rotate_x.to_bits(), f.topn_rotate_z.to_bits()],
            joint4,
        );
        let want = (
            row.status, row.lr, row.air, row.vel, row.pos, row.rot, row.joint4,
        );
        assert_eq!(
            got, want,
            "{what} tick {tick}: (status, lr, air, vel_air, pos, rot, joint4)"
        );
    }
    assert!(rows.next().is_none(), "every row compared");
}


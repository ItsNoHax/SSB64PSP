//! Mushroom Kingdom (`grinishie.c`, `ftcommondokan.c`, `itpakkun.c`) VS
//! replays against an N64 trace: the pipes, the Piranha Plants they
//! notify, the balance scales and the POW Block, on the stage's own
//! controller and items.
//!
//! The trace is a warp ROM (`mkrom_vs2.py`, Mario vs Mario on gkind 8)
//! sampled each frame by `vs_in.py`, whose reactive controller walks
//! P2 into the pipes; `inrows.py` turns it into rows.
//!
//! The N64 measurements are embedded (`PIPE_*` for the pipe/scale/POW
//! run, `FB_*` for the fireball run; [`vs_replay::Trace`]): each run's
//! pad and seed changes and the rows at every tenth tick plus every tick
//! a fighter status, the scale status, a plant status or percent, the POW
//! status or the item count changes. `INISHIE_ROWS` optionally lists full
//! per-tick traces (`:` apart, outside git) to replay as well.
//!
//! Per row, whitespace-separated: `t`, each fighter
//! `status x y`, the scales `alt accelerate wait status y0 y1`, each
//! plant `status multi y percent` (status 0 Wait, 1 Appear, 2 Damaged from its
//! `proc_update`), the POW Block's `appear_wait status`, then the count
//! of other items and each one's `kind x y`. N64 row `t` follows frame
//! `t`; the pads it lists act on frame `t + 1`.


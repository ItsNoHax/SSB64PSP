/// The stage's columns of one row.
struct Cols {
    scale: [f32; 6],
    /// `status multi y percent`; percent -1 where the trace has none.
    plants: [(u8, u16, f32, i32); 2],
    pblock: (u16, u8),
    items: Vec<(u32, f32, f32)>,
}

fn cols(w: &[String]) -> Cols {
    let f = |i: usize| w[i].parse::<f32>().unwrap();
    let n: usize = w[16].parse().unwrap();
    Cols {
        scale: [f(0), f(1), f(2), f(3), f(4), f(5)],
        plants: [0, 4].map(|o| {
            let (s, m, p) = (&w[6 + o], &w[7 + o], &w[9 + o]);
            (
                s.parse().unwrap(),
                m.parse().unwrap(),
                f(8 + o),
                p.parse().unwrap(),
            )
        }),
        pblock: (w[14].parse().unwrap(), w[15].parse().unwrap()),
        items: (0..n)
            .map(|i| (w[17 + 3 * i].parse().unwrap(), f(18 + 3 * i), f(19 + 3 * i)))
            .collect(),
    }
}

fn check(row: &vs_replay::Row, pair: &posed::Pair, _: &[posed::Posed]) -> Vec<String> {
    let row = cols(&row.rest);
    let mut bad = Vec::new();
    let c = pair.stage.inishie().unwrap();
    let scale = [
        c.alt,
        c.accelerate,
        f32::from(c.wait),
        c.status as u8 as f32,
        c.platform[0].y,
        c.platform[1].y,
    ];
    if scale
        .iter()
        .zip(row.scale)
        .any(|(a, b)| (a - b).abs() > 1e-3)
    {
        bad.push(format!("scale host {scale:?} n64 {:?}", row.scale));
    }
    for (i, &(st, multi, y, pc)) in row.plants.iter().enumerate() {
        let it = pair.items.items().find(|it| {
            it.kind == ssb_game::item::ItemKind::Pakkun && usize::from(it.vars.pakkun_index) == i
        });
        let host = it.map(|it| {
            let s = match it.status {
                ssb_game::item::ItemStatus::Pakkun(s) => s as u8,
                _ => 9,
            };
            (s, it.multi, it.pos.y, it.percent_damage)
        });
        if host.is_none_or(|(s, m, hy, hp)| {
            s != st || m != multi || (hy - y).abs() > 1e-3 || (pc >= 0 && hp != pc)
        }) {
            bad.push(format!("plant{i} host {host:?} n64 {st} {multi} {y} {pc}"));
        }
    }
    let pblock = (c.pblock_wait, c.pblock_status as u8);
    if pblock != row.pblock {
        bad.push(format!("pblock host {pblock:?} n64 {:?}", row.pblock));
    }
    let items: Vec<(f32, f32)> = pair
        .items
        .items()
        .filter(|it| it.kind != ssb_game::item::ItemKind::Pakkun)
        .map(|it| (it.pos.x, it.pos.y))
        .collect();
    let want: Vec<(f32, f32)> = row.items.iter().map(|&(_, x, y)| (x, y)).collect();
    if items.len() != want.len()
        || items
            .iter()
            .zip(&want)
            .any(|(a, b)| (a.0 - b.0).abs() > 1e-3 || (a.1 - b.1).abs() > 1e-3)
    {
        bad.push(format!("items host {items:?} n64 {want:?}"));
    }
    bad
}


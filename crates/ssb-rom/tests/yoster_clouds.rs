//! Yoshi's Island (`gryoster.c`) VS replays against an N64 trace: the
//! three clouds that sink under a fighter, evaporate and come back, on
//! the stage's own controller and the clouds' material scripts.
//!
//! The trace is a warp ROM (`mkrom_vs2.py yoster vs 5 0 0 0 0 0`, Mario vs
//! Mario on gkind 5) sampled each frame by `vs_in.py` (`STAGE=yoster`),
//! with P1's open-loop script (designed on the host first):
//!
//! `391:400:x=-80;446:3:x=-80+c_u;475:3:x=-80+c_u;500:400:;660:400:x=80;660:3:x=80+c_u;720:3:x=40+y=80+b;770:400:`
//!
//! P1 dashes off the island, double-jumps onto the left cloud and stands
//! until its pressure timer runs out; the cloud evaporates under him, he
//! recovers to the left platform, and the cloud reforms. `yrows.py` turns
//! the trace into rows.
//!
//! The N64 measurements are embedded (`YOSTER_*`; [`vs_replay::Trace`]):
//! the run's pad and seed changes and the rows at every tenth tick plus
//! every tick a cloud's status, anim or line flag changes. `YOSTER_ROWS`
//! optionally lists full per-tick traces (`:` apart, outside git) to
//! replay as well.
//!
//! Per row, after the fighters ([`vs_replay`]): each cloud's
//! `status anim_id is_cloud_line_active pressure_timer evaporate_wait
//! pressure y`, `y` being the cloud root `DObj`'s.

use ssb_game::fighter::Facing;
use ssb_game::stage::yoster::CloudStatus;

#[path = "common/posed.rs"]

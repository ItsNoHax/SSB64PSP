#[path = "common/dream_land.rs"]
mod dream_land;

#[path = "common/vs_replay.rs"]
mod vs_replay;
use vs_replay::{replay_env, Trace, Vs};

const VS: Vs = Vs {
    // `nGRKindYoster`.
    gkind: 5,
    // Just above the floors: the trace rounds y to two decimals, a hair
    // below the slopes, and `init_floor` drops each onto its line.
    spawns: [
        (629.0, -299.0, Facing::Left, 270),
        (90.0, 2215.5, Facing::Right, 330),
    ],
    go: 390,
};

fn check(row: &vs_replay::Row, pair: &posed::Pair, _: &[posed::Posed]) -> Vec<String> {
    let c = pair.stage.yoster().unwrap();
    let mut bad = Vec::new();
    for (i, cloud) in c.clouds.iter().enumerate() {
        let w = &row.rest[7 * i..7 * i + 7];
        let n = |k: usize| w[k].parse::<i32>().unwrap();
        let f = |k: usize| w[k].parse::<f32>().unwrap();
        let status = match cloud.status {
            CloudStatus::Solid => 0,
            CloudStatus::Evaporate => 1,
        };
        // `grYosterUpdateCloudAnim` plays and clears `anim_id` each frame.
        let anim = cloud.anim.map_or(-1, |a| a as i32);
        let host = (
            status,
            anim,
            i32::from(cloud.is_line_active),
            i32::from(cloud.pressure_timer),
        );
        let n64 = (n(0), n(1), n(2), n(3));
        if host != n64
            || i32::from(cloud.evaporate_wait) != n(4)
            || (cloud.pressure - f(5)).abs() > 1e-3
            || (cloud.pos.y - f(6)).abs() > 1e-3
        {
            bad.push(format!(
                "cloud{i} host {host:?} {} {} {} n64 {w:?}",
                cloud.evaporate_wait, cloud.pressure, cloud.pos.y
            ));
        }
    }
    bad
}

/// Mario stands on the left cloud for its 120 frames: it sinks 180,
/// evaporates (its line off for 180 frames) and comes back once its
/// Solid material script ends.
#[test]
#[cfg_attr(ssb64_stub_tables, ignore = "needs the ROM-generated tables")]
fn yoshis_island_clouds_sink_evaporate_and_reform_as_on_the_n64() {
    replay_env("YOSTER_ROWS", &VS, &[&YOSTER], check);
}


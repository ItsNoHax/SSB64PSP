/// An effect descriptor's `dl_link`: the byte after `flags` in `EFDesc`.
const fn dl_link(name: &'static str, symbol: &'static str, vram: u32) -> DArray {
    DArray::new(name, symbol, OVL2, vram + 1, Elem::U8, &[1])
}
